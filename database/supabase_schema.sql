-- Policies for public catalog tables
DROP POLICY IF EXISTS "Allow read access to application statuses" ON application_statuses;
CREATE POLICY "Allow read access to application statuses" ON application_statuses FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow read access to skills" ON skills;
CREATE POLICY "Allow read access to skills" ON skills FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow authenticated users to insert skills" ON skills;
CREATE POLICY "Allow authenticated users to insert skills" ON skills FOR INSERT WITH CHECK (auth.role() = 'authenticated' OR auth.role() = 'service_role');

-- Policies for users
DROP POLICY IF EXISTS "Users can read own profile or admin can read all" ON users;
CREATE POLICY "Users can read own profile or admin can read all" ON users FOR SELECT USING (
    auth.uid()::text = id::text OR auth.jwt() ->> 'role' = 'admin' OR auth.role() = 'service_role'
);

DROP POLICY IF EXISTS "Users can update own profile" ON users;
CREATE POLICY "Users can update own profile" ON users FOR UPDATE USING (auth.uid()::text = id::text OR auth.role() = 'service_role');

-- Policies for applications
DROP POLICY IF EXISTS "Students can select own applications or admin can read all" ON applications;
CREATE POLICY "Students can select own applications or admin can read all" ON applications FOR SELECT USING (
    student_id::text = auth.uid()::text OR auth.jwt() ->> 'role' = 'admin' OR auth.role() = 'service_role'
);

DROP POLICY IF EXISTS "Students can insert own applications" ON applications;
CREATE POLICY "Students can insert own applications" ON applications FOR INSERT WITH CHECK (
    student_id::text = auth.uid()::text OR auth.role() = 'service_role'
);

DROP POLICY IF EXISTS "Students can update own applications" ON applications;
CREATE POLICY "Students can update own applications" ON applications FOR UPDATE USING (
    student_id::text = auth.uid()::text OR auth.role() = 'service_role'
);

DROP POLICY IF EXISTS "Students can delete own applications" ON applications;
CREATE POLICY "Students can delete own applications" ON applications FOR DELETE USING (
    student_id::text = auth.uid()::text OR auth.role() = 'service_role'
);

-- Policies for history
DROP POLICY IF EXISTS "Students can select own status history" ON application_status_history;
CREATE POLICY "Students can select own status history" ON application_status_history FOR SELECT USING (
    EXISTS (
        SELECT 1 FROM applications 
        WHERE applications.id = application_status_history.application_id 
          AND (applications.student_id::text = auth.uid()::text OR auth.jwt() ->> 'role' = 'admin')
    ) OR auth.role() = 'service_role'
);

DROP POLICY IF EXISTS "Students can insert status history for own applications" ON application_status_history;
CREATE POLICY "Students can insert status history for own applications" ON application_status_history FOR INSERT WITH CHECK (
    EXISTS (
        SELECT 1 FROM applications 
        WHERE applications.id = application_status_history.application_id 
          AND applications.student_id::text = auth.uid()::text
    ) OR auth.role() = 'service_role'
);

-- Policies for student skills
DROP POLICY IF EXISTS "Students can manage own skills" ON student_skills;
CREATE POLICY "Students can manage own skills" ON student_skills FOR ALL
    USING (student_id::text = auth.uid()::text OR auth.role() = 'service_role')
    WITH CHECK (student_id::text = auth.uid()::text OR auth.role() = 'service_role');

